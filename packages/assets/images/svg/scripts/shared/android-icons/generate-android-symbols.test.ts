import { mkdtemp, readdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, test } from 'vitest';
import { ANDROID_ICON_SIZES } from './android-icons-config.ts';
import { buildAndroidSymbolFile, generateAndroidSymbols } from './generate-android-symbols.ts';

const EXPECTED_LOCK_SYMBOL = `// This file is auto-generated by the Android icons build of the Infomaniak design-system repository. Do not edit it manually.
package com.infomaniak.designsystem.icons.symbols

import androidx.compose.ui.graphics.vector.ImageVector
import com.infomaniak.designsystem.icons.EsdsIcons
import com.infomaniak.designsystem.icons.imagevector.extrasmall.Lock
import com.infomaniak.designsystem.icons.imagevector.small.Lock
import com.infomaniak.designsystem.icons.imagevector.medium.Lock
import com.infomaniak.designsystem.icons.imagevector.large.Lock
import com.infomaniak.designsystem.icons.imagevector.extralarge.Lock

val EsdsIcons.Lock: Symbol get() = LockSymbol

private object LockSymbol : Symbol {
    override val ExtraSmall: ImageVector get() = EsdsIcons.ExtraSmall.Lock
    override val Small: ImageVector get() = EsdsIcons.Small.Lock
    override val Medium: ImageVector get() = EsdsIcons.Medium.Lock
    override val Large: ImageVector get() = EsdsIcons.Large.Lock
    override val ExtraLarge: ImageVector get() = EsdsIcons.ExtraLarge.Lock
}
`;

function buildIconNamesBySize(
  iconNames: readonly string[],
): ReadonlyMap<string, readonly string[]> {
  return new Map(ANDROID_ICON_SIZES.map(({ name }) => [name, iconNames]));
}

describe('buildAndroidSymbolFile', () => {
  test('groups every size of the icon behind a Symbol', () => {
    expect(buildAndroidSymbolFile('Lock')).toBe(EXPECTED_LOCK_SYMBOL);
  });
});

describe('generateAndroidSymbols', () => {
  let outputDirectory: string;

  beforeEach(async () => {
    outputDirectory = join(await mkdtemp(join(tmpdir(), 'android-symbols-')), 'symbols');
  });

  afterEach(async () => {
    await rm(join(outputDirectory, '..'), { force: true, recursive: true });
  });

  test('writes one sorted symbol file per icon', async () => {
    expect(
      await generateAndroidSymbols({
        outputDirectory,
        iconNamesBySize: buildIconNamesBySize(['Lock', 'Check']),
      }),
    ).toEqual(['Check', 'Lock']);

    expect(await readdir(outputDirectory)).toEqual(['Check.kt', 'Lock.kt']);
    expect(await readFile(join(outputDirectory, 'Lock.kt'), 'utf8')).toBe(EXPECTED_LOCK_SYMBOL);
  });

  test('throws when an icon is missing in a size', async () => {
    const iconNamesBySize = new Map(buildIconNamesBySize(['Lock', 'Check']));
    iconNamesBySize.set('Small', ['Lock']);

    await expect(generateAndroidSymbols({ outputDirectory, iconNamesBySize })).rejects.toThrow(
      'Icons missing in some sizes: Small.Check.',
    );
    await expect(readdir(outputDirectory)).rejects.toThrow();
  });

  test('throws when a size has no icon at all', async () => {
    const iconNamesBySize = new Map(buildIconNamesBySize(['Lock']));
    iconNamesBySize.delete('Large');

    await expect(generateAndroidSymbols({ outputDirectory, iconNamesBySize })).rejects.toThrow(
      'Icons missing in some sizes: Large.Lock.',
    );
  });
});
