import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildIconNameList } from '../../../src/core/icon-names.ts';

const MODULE_DIR: string = dirname(fileURLToPath(import.meta.url));
const PACKAGE_DIR: string = join(MODULE_DIR, '../../..');
/** Repo root, then into the svg-assets package: the Figma-feed icon set. */
const ICON_SVG_DIR: string = join(
  PACKAGE_DIR,
  '..',
  '..',
  'assets',
  'images',
  'svg',
  'assets',
  'svg',
  'monotone',
  'figma',
);
const GENERATED_DIR: string = join(PACKAGE_DIR, 'src', 'core', 'generated');

/**
 * Regenerates the icon-name inventory consumed by the component rules from the
 * svg-assets package. The file is gitignored and generated on demand — the
 * output is deterministic (sorted), so it only changes when the icon assets
 * change.
 */
export async function generateIconNameInventory(): Promise<void> {
  const entries: readonly string[] = await readdir(ICON_SVG_DIR);
  const iconNames: readonly string[] = buildIconNameList(entries);

  await mkdir(GENERATED_DIR, { recursive: true });
  await writeFile(
    join(GENERATED_DIR, 'icon-names.ts'),
    [
      '// Generated by generate-icon-names from the svg-assets package',
      '// (assets/svg/monotone/figma/*.svg) — do not edit.',
      '',
      'export const ICON_NAMES: readonly string[] = [',
      ...iconNames.map((name: string): string => `  '${name}',`),
      '];',
      '',
    ].join('\n'),
    'utf-8',
  );
}
